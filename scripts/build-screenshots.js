// Usage (project folder la irundhu):  node scripts/build-screenshots.js
// assets/screenshots/<project-id>/ folders scan panni js/screenshots-manifest.js generate pannum.
// Homepage.png first (cover), mathadhu filename order la.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "assets", "screenshots");
const exts = /\.(png|jpe?g|webp|gif|avif)$/i;
const manifest = {};

for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const files = fs.readdirSync(path.join(root, entry.name))
    .filter((name) => exts.test(name))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
  const cover = files.findIndex((name) => /^homepage\./i.test(name));
  if (cover > 0) files.unshift(files.splice(cover, 1)[0]);
  if (files.length) manifest[entry.name] = files;
}

const output = `// AUTO-GENERATED by scripts/build-screenshots.js - edit pannadheenga.\nconst screenshotManifest = ${JSON.stringify(manifest, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, "..", "js", "screenshots-manifest.js"), output);
console.log("Done:", Object.entries(manifest).map(([id, f]) => `${id} (${f.length})`).join(", "));
